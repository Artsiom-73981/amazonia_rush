//! Seals the quiet side's plaintext inputs into `oracle/src/gate_table.rs`.
//!
//! Run from the workspace root:
//!
//!     cargo run -p lexicon_forge --bin seal_gate
//!
//! Reads `oracle/tools/gate.txt`, writes ciphertext. Keeping the plaintext in
//! the repo and the seal in the binary is the same bargain the lexicon makes.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[path = "../../../oracle/src/entropy.rs"]
mod entropy;
#[path = "../../../oracle/src/crypt.rs"]
mod crypt;

use crypt::{gate_key, shroud, unshroud};
use entropy::imprint;

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("oracle");
    let plain_source = root.join("tools").join("gate.txt");
    let sealed_source = root.join("tools").join("gate.sealed");

    // The sealed file is the one in the repository. The plaintext is read only
    // when it exists, which is during local editing and never in CI.
    let raw = if plain_source.exists() {
        match fs::read_to_string(&plain_source) {
            Ok(text) => text,
            Err(why) => {
                eprintln!("cannot read {}: {why}", plain_source.display());
                std::process::exit(2);
            }
        }
    } else {
        let bytes = match fs::read(&sealed_source) {
            Ok(bytes) => bytes,
            Err(_) => {
                eprintln!(
                    "neither {} nor {} is readable",
                    plain_source.display(),
                    sealed_source.display()
                );
                std::process::exit(2);
            }
        };
        let passphrase = match std::env::var("AMZORA_PASSPHRASE") {
            Ok(value) if !value.is_empty() => value,
            _ => {
                eprintln!(
                    "AMZORA_PASSPHRASE is not set: needed to open {}",
                    sealed_source.display()
                );
                std::process::exit(2);
            }
        };
        let key = source_key(&passphrase);
        match source_plain(&bytes, key) {
            Some(text) => String::from_utf8(text).unwrap_or_else(|_| {
                eprintln!("the opened source is not utf8");
                std::process::exit(2);
            }),
            None => {
                eprintln!("wrong passphrase, or {} is damaged", sealed_source.display());
                std::process::exit(5);
            }
        }
    };

    // Ordered slots: the index inside this vector IS the slot number Swift
    // asks for, so a reordering here renumbers the protocol.
    let order = [
        "gate.endpoint",
        "gate.privacy",
        "gate.support",
        "gate.attribution_key",
        "gate.sender",
        "gate.bundle",
        "gate.store",
        "gate.title",
        "gate.nse_suffix",
        // The Firebase identity, in the order the app rebuilds it.
        "gate.fb_api_key",
        "gate.fb_project",
        "gate.fb_bucket",
        "gate.fb_app_id",
    ];

    let mut values: BTreeMap<String, String> = BTreeMap::new();
    for line in raw.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some(split) = trimmed.find('=') else { continue };
        let key = trimmed[..split].trim().to_string();
        if key.is_empty() {
            continue;
        }
        values.insert(key, trimmed[split + 1..].trim().to_string());
    }

    let mut payload_parts: Vec<(&str, String)> = Vec::new();
    for key in order {
        match values.get(key) {
            Some(value) => payload_parts.push((key, value.clone())),
            None => {
                eprintln!("gate input is missing required key: {key}");
                std::process::exit(2);
            }
        }
    }

    let phrases: Vec<String> = payload_parts.iter().map(|(_, v)| v.clone()).collect();
    let blob = pack(&phrases);
    let ua = ua_fragments();

    let mut rust = String::new();
    rust.push_str("// @generated by `cargo run -p lexicon_forge --bin seal_gate`. Do not edit.\n");
    rust.push_str("//\n// The quiet side's addresses and keys, sealed. Change\n");
    rust.push_str("// `oracle/tools/gate.txt` (or the UA fragments below) and re-run.\n\n");

    let _ = write!(rust, "pub const GATE_BLOB: &[u8] = &[");
    for (index, byte) in blob.iter().enumerate() {
        if index % 20 == 0 {
            rust.push_str("\n    ");
        }
        let _ = write!(rust, "{byte:#04x}, ");
    }
    rust.push_str("\n];\n\n");

    // User-Agent fragments. Sealed the same way, opened one at a time by the
    // app and concatenated at runtime, so no recognisable header scaffolding
    // is present as a readable string anywhere in the binary.
    // Index-aligned with ua_fragments(): the handle the app asks for is the
    // position in that vector, so the two lists must never drift apart.
    let names = [
        "UA_PRODUCT",
        "UA_PLATFORM_PREFIX",
        "UA_PLATFORM_SUFFIX",
        "UA_ENGINE",
        "UA_VERSION_TAIL",
        "UA_MOBILE",
        "UA_SAFARI_TAIL",
        "UA_STYLE",
        "UA_SETTER",
        "UA_SEP",
    ];
    for (name, fragment) in names.iter().zip(ua.iter()) {
        let sealed = shroud(fragment.as_bytes(), ua_key(name));
        let _ = write!(rust, "pub const {name}: &[u8] = &[");
        for (index, byte) in sealed.iter().enumerate() {
            if index % 20 == 0 {
                rust.push_str("\n    ");
            }
            let _ = write!(rust, "{byte:#04x}, ");
        }
        rust.push_str("\n];\n\n");
    }

    let out = root.join("src").join("gate_table.rs");
    if let Err(why) = fs::write(&out, rust) {
        eprintln!("cannot write {}: {why}", out.display());
        std::process::exit(3);
    }
    println!(
        "sealed {} gate slots ({}B) and {} ua fragments -> {}",
        payload_parts.len(),
        blob.len(),
        ua.len(),
        out.display()
    );
    println!("  gate_key {:#018x}", gate_key());
}

/// The User-Agent the app presents. Assembled from real device facts at
/// runtime; only these fixed scaffolding fragments are sealed here.
fn ua_fragments() -> Vec<String> {
    vec![
        // 0 product token
        "Mozilla/5.0".to_string(),
        // 1 platform prefix, ends where the OS version goes
        "(iPhone; CPU iPhone OS ".to_string(),
        // 2 platform tail, closes the parenthesised group
        " like Mac OS X)".to_string(),
        // 3 engine
        "AppleWebKit/605.1.15 (KHTML, like Gecko)".to_string(),
        // 4 version token preceding the mobile token
        "Version/604.1".to_string(),
        // 5 mobile token
        "Mobile/15E148".to_string(),
        // 6 safari token
        "Safari/604.1".to_string(),
        // 7 the model segment: semicolon and a gap before the model name
        "; ".to_string(),
        // 8 the web view setter, looked up by name only
        "setCustomUserAgent:".to_string(),
        // 9 the spacer that joins the parts
        " ".to_string(),
    ]
}


/// A per-fragment key so one opened fragment does not open the rest.
fn ua_key(name: &str) -> u64 {
    let bytes = name.as_bytes();
    let mut acc = 0x1F3B_7E29_C4D8_5601u64;
    for byte in bytes {
        acc ^= *byte as u64;
        acc = acc.rotate_left(11).wrapping_mul(0x9E37_79B9_7F4A_7C15);
    }
    acc ^ 0x5D02_A18C_F43E_96B7
}

/// Count, then an (offset, length) table, then the text run, all sealed.
fn pack(phrases: &[String]) -> Vec<u8> {
    let mut table = Vec::new();
    let mut body = Vec::new();
    let header = 2 + phrases.len() * 6;
    for phrase in phrases {
        let bytes = phrase.as_bytes();
        let offset = (header + body.len()) as u32;
        table.extend_from_slice(&offset.to_le_bytes());
        table.extend_from_slice(&(bytes.len() as u16).to_le_bytes());
        body.extend_from_slice(bytes);
    }
    let mut payload = Vec::with_capacity(header + body.len());
    payload.extend_from_slice(&(phrases.len() as u16).to_le_bytes());
    payload.extend_from_slice(&table);
    payload.extend_from_slice(&body);
    shroud(&payload, gate_key())
}

/// Derives the envelope key from the passphrase. Salted so the same passphrase
/// used for another purpose never yields the same key.
fn source_key(passphrase: &str) -> u64 {
    let salted = format!("amzora.gate.v1|{passphrase}");
    imprint(salted.as_bytes(), 0x51C3_9E7B_2D48_A0F6)
}

/// Opens the sealed source file.
fn source_plain(sealed: &[u8], key: u64) -> Option<Vec<u8>> {
    unshroud(sealed, key)
}
