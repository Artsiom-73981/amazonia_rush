//! Compiles `oracle/tools/lexicon*.txt` into a shrouded byte table plus the
//! numeric handles used by Rust and Swift. Run from the workspace root:
//!
//!     cargo run -p lexicon_forge
//!
//! Keeping the plaintext in the repo and the ciphertext in the binary is the
//! whole point: the shipped app carries no readable copy.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[path = "../../oracle/src/entropy.rs"]
mod entropy;
#[path = "../../oracle/src/crypt.rs"]
mod crypt;

use crypt::{lexicon_key, shroud};

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("oracle");
    let tools = root.join("tools");

    // English is the master: it fixes the key order, and therefore every
    // numeric handle. A translation may only fill those same slots.
    let (keys, phrases) = read_pairs(&tools.join("lexicon.txt"));
    if keys.is_empty() {
        eprintln!("the master lexicon is empty");
        std::process::exit(2);
    }

    let mut tongues: Vec<(&str, Vec<String>)> = vec![("", phrases.clone())];
    for (tag, leaf) in [("RU", "ru/lexicon.txt")] {
        let path = tools.join(leaf);
        if !path.exists() {
            continue;
        }
        let (other_keys, other_phrases) = read_pairs(&path);
        let mut lookup: BTreeMap<&str, &str> = BTreeMap::new();
        for (key, phrase) in other_keys.iter().zip(other_phrases.iter()) {
            lookup.insert(key.as_str(), phrase.as_str());
        }
        let mut missing: Vec<&str> = Vec::new();
        let mut filled = Vec::with_capacity(keys.len());
        for (index, key) in keys.iter().enumerate() {
            match lookup.get(key.as_str()) {
                Some(phrase) => filled.push((*phrase).to_string()),
                None => {
                    missing.push(key.as_str());
                    filled.push(phrases[index].clone());
                }
            }
        }
        let spare: Vec<&str> = other_keys
            .iter()
            .map(|key| key.as_str())
            .filter(|key| !keys.iter().any(|master| master == key))
            .collect();
        if !missing.is_empty() {
            println!("  {tag}: {} keys fall back to English: {:?}", missing.len(), &missing[..missing.len().min(6)]);
        }
        if !spare.is_empty() {
            println!("  {tag}: {} keys the master does not have: {:?}", spare.len(), &spare[..spare.len().min(6)]);
        }
        tongues.push((tag, filled));
    }

    let cloaked = pack(&phrases, keys.len());

    // Families such as `scarab.name.0 .. scarab.name.7` also get an array so
    // call sites can index by content id instead of naming each constant.
    let mut families: BTreeMap<String, Vec<(u32, u16)>> = BTreeMap::new();
    let mut rust = String::new();
    rust.push_str("// @generated by `cargo run -p lexicon_forge`. Do not edit.\n\n");
    let mut scrolls: Vec<(String, usize)> = Vec::new();
    for (tag, filled) in &tongues {
        let blob = if tag.is_empty() {
            cloaked.clone()
        } else {
            pack(filled, keys.len())
        };
        let name = if tag.is_empty() {
            "SCROLL".to_string()
        } else {
            format!("SCROLL_{tag}")
        };
        let _ = write!(rust, "pub const {name}: &[u8] = &[");
        for (index, byte) in blob.iter().enumerate() {
            if index % 20 == 0 {
                rust.push_str("\n    ");
            }
            let _ = write!(rust, "{byte:#04x}, ");
        }
        rust.push_str("\n];\n\n");
        scrolls.push((name, blob.len()));
    }
    let listing = scrolls
        .iter()
        .map(|(name, _)| name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        rust,
        "/// Every compiled tongue, in the order the app numbers them.\npub const SCROLLS: [&[u8]; {}] = [{listing}];\n",
        scrolls.len()
    );

    let mut swift = String::new();
    swift.push_str("// @generated by `cargo run -p lexicon_forge`. Do not edit.\n\n");
    swift.push_str("enum Lexeme {\n");

    for (index, key) in keys.iter().enumerate() {
        let handle = index as u16;
        let (stem, ordinal) = split_family(key);
        if let Some(ordinal) = ordinal {
            families.entry(stem).or_default().push((ordinal, handle));
        }
        let _ = writeln!(rust, "pub const {}: u16 = {handle};", rust_name(key));
        let _ = writeln!(swift, "    static let {}: UInt16 = {handle}", swift_name(key));
    }

    rust.push('\n');
    for (stem, mut slots) in families {
        if slots.len() < 2 {
            continue;
        }
        slots.sort_by_key(|slot| slot.0);
        let dense = slots
            .iter()
            .enumerate()
            .all(|(seat, slot)| slot.0 as usize == seat);
        if !dense {
            continue;
        }
        let listing = slots
            .iter()
            .map(|slot| slot.1.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        let bare = rust_name(&stem);
        let _ = writeln!(
            rust,
            "pub const G_{}: [u16; {}] = [{listing}];",
            bare.trim_start_matches("L_"),
            slots.len()
        );
        let _ = writeln!(
            swift,
            "    static let {}: [UInt16] = [{listing}]",
            swift_name(&format!("{stem}.all"))
        );
    }
    swift.push_str("}\n");

    let rust_out = root.join("src").join("lexicon_table.rs");
    let swift_out = root
        .join("..")
        .join("App")
        .join("Generated")
        .join("Lexeme.swift");
    if let Some(parent) = swift_out.parent() {
        let _ = fs::create_dir_all(parent);
    }
    if let Err(why) = fs::write(&rust_out, rust) {
        eprintln!("cannot write {}: {why}", rust_out.display());
        std::process::exit(3);
    }
    if let Err(why) = fs::write(&swift_out, swift) {
        eprintln!("cannot write {}: {why}", swift_out.display());
        std::process::exit(3);
    }
    println!(
        "forged {} lexemes in {} tongues -> {}",
        keys.len(),
        scrolls.len(),
        scrolls
            .iter()
            .map(|(name, span)| format!("{name} {span}B"))
            .collect::<Vec<_>>()
            .join(", ")
    );
}

/// Reads a `key = value` file, keeping the file's own order.
fn read_pairs(path: &PathBuf) -> (Vec<String>, Vec<String>) {
    let raw = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(why) => {
            eprintln!("cannot read {}: {why}", path.display());
            std::process::exit(2);
        }
    };
    let mut keys = Vec::new();
    let mut phrases = Vec::new();
    for line in raw.lines() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some(split) = trimmed.find('=') else {
            continue;
        };
        let key = trimmed[..split].trim().to_string();
        if key.is_empty() {
            continue;
        }
        keys.push(key);
        phrases.push(trimmed[split + 1..].trim().replace("\\n", "\n"));
    }
    (keys, phrases)
}

/// Count, then an (offset, length) table, then the text run, all shrouded.
fn pack(phrases: &[String], count: usize) -> Vec<u8> {
    let mut table = Vec::new();
    let mut body = Vec::new();
    let header = 2 + count * 6;
    for phrase in phrases {
        let bytes = phrase.as_bytes();
        let offset = (header + body.len()) as u32;
        table.extend_from_slice(&offset.to_le_bytes());
        table.extend_from_slice(&(bytes.len() as u16).to_le_bytes());
        body.extend_from_slice(bytes);
    }
    let mut payload = Vec::with_capacity(header + body.len());
    payload.extend_from_slice(&(count as u16).to_le_bytes());
    payload.extend_from_slice(&table);
    payload.extend_from_slice(&body);
    shroud(&payload, lexicon_key())
}

fn split_family(key: &str) -> (String, Option<u32>) {
    let Some(cut) = key.rfind('.') else {
        return (key.to_string(), None);
    };
    let tail = &key[cut + 1..];
    match tail.parse::<u32>() {
        Ok(ordinal) => (key[..cut].to_string(), Some(ordinal)),
        Err(_) => (key.to_string(), None),
    }
}

fn rust_name(key: &str) -> String {
    let mut out = String::from("L_");
    for ch in key.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
        } else {
            out.push('_');
        }
    }
    out
}

fn swift_name(key: &str) -> String {
    let mut out = String::new();
    let mut raise = false;
    for ch in key.chars() {
        if ch.is_ascii_alphanumeric() {
            if raise {
                out.push(ch.to_ascii_uppercase());
                raise = false;
            } else {
                out.push(ch);
            }
        } else {
            raise = true;
        }
    }
    if out
        .chars()
        .next()
        .map(|ch| ch.is_ascii_digit())
        .unwrap_or(true)
    {
        out.insert(0, 'x');
    }
    out
}
